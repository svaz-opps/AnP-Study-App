// Checks that an open round survives a live page update (window.claude.hot snapshot/ready).
import { createRequire } from 'module';
import path from 'path';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const file = 'file://' + path.resolve(path.dirname(new URL(import.meta.url).pathname), '../dist/ward-rounds.html');
const shim = (data) => `window.claude = { use: async () => null, hot: { snapshot(fn) { window.__snap = fn; }, ready(cb) { cb(${JSON.stringify(data)}); } } };`;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1180, height: 820 } });
let page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.addInitScript(shim({}));
await page.goto(file);
await page.waitForSelector('.onboard');
for (const t of ['1', '2', '3', '4', '5']) await page.click(`[data-to="${t}"]`);
await page.waitForSelector('.chart .opt');
await page.evaluate(() => { const q = window.WR.App.run.q; if (q.type === 'mcq' || q.type === 'priority' || q.type === 'teaching' || q.type === 'math') document.querySelector(`.opt[data-i="${q.opts.findIndex((o) => o.c)}"]`).click(); const s = document.querySelector('[data-action="submit"]'); if (s && !s.disabled) s.click(); });
const before = await page.evaluate(() => ({ snap: JSON.parse(JSON.stringify(window.__snap())), qid: window.WR.App.run.cur.qid, score: window.WR.App.run.score, idx: window.WR.App.run.idx }));
await page.close();
page = await ctx.newPage();
page.on('pageerror', (e) => errs.push(e.message));
await page.addInitScript(shim(before.snap));
await page.goto(file);
await page.waitForSelector('.chart .opt');
const after = await page.evaluate(() => ({ name: window.WR.App.name, qid: window.WR.App.run.cur.qid, score: window.WR.App.run.score, idx: window.WR.App.run.idx, n: window.WR.App.run.cfg.n }));
const ok = after.name === 'chart' && after.qid === before.qid && after.score === before.score && after.idx === before.idx && after.n === 10 && !errs.length;
console.log(ok ? 'HOT RESTORE PASSED' : 'HOT RESTORE FAILED ' + JSON.stringify({ before: { qid: before.qid, score: before.score }, after, errs }));
await browser.close();
process.exit(ok ? 0 : 1);
